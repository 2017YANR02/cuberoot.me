import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import postgres from 'postgres';
import { Hono, type Context } from 'hono';
import { HTTPException } from 'hono/http-exception';
import { beforeAll, afterAll, beforeEach, describe, expect, it, vi } from 'vitest';

const connection = vi.hoisted(() => ({ query: vi.fn(), withTransaction: vi.fn() }));
vi.mock('../src/db/connection.js', () => connection);
vi.mock('../src/utils/recon_helpers.js', () => {
  const users = {
    owner: { wcaId: '2000TEST01', uid: 1, name: 'Owner', isAdmin: false },
    other: { wcaId: '2000TEST02', uid: 2, name: 'Other', isAdmin: false },
    admin: { wcaId: '2000TEST03', uid: 3, name: 'Admin', isAdmin: true },
  };
  const authenticateUser = async (header?: string) => users[header?.replace('Bearer ', '') as keyof typeof users] ?? null;
  const requireAuth = async (c: Context) => {
    const user = await authenticateUser(c.req.header('Authorization'));
    if (!user) throw new HTTPException(401);
    return user;
  };
  return { authenticateUser, requireAuth, checkRateLimit: vi.fn(), requireAdmin: async (c: Context) => {
    const user = await requireAuth(c);
    if (!user.isAdmin) throw new HTTPException(403);
    return user;
  } };
});
import { articleRoutes } from '../src/routes/article.js';
import { membershipRoutes } from '../src/routes/membership.js';
import { membershipGalleryRoutes } from '../src/routes/membership_gallery.js';

const url = process.env.GALLERY_TEST_DATABASE_URL;
describe.skipIf(!url)('gallery privacy and review against isolated PostgreSQL', () => {
  const schema = `gallery_${randomUUID().replaceAll('-', '')}`;
  let admin: ReturnType<typeof postgres>, db: ReturnType<typeof postgres>;
  const app = new Hono().route('/v1', articleRoutes).route('/v1', membershipRoutes).route('/v1', membershipGalleryRoutes);
  const request = (path: string, actor?: string, method = 'GET', body?: unknown) => app.request(`/v1${path}`, {
    method, headers: { 'Content-Type': 'application/json', ...(actor ? { Authorization: `Bearer ${actor}` } : {}) },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  const visibility = (status: string, actor = 'owner') => request('/membership/gallery/1/visibility', actor, 'PUT', { status });
  const review = (decision: string, actor = 'admin') => request('/membership/gallery/1/review', actor, 'POST', { decision });
  const save = (imageIds: number[]) => request('/membership/me/profile', 'owner', 'PUT', { intro: '', imageIds, showInMemberList: false });

  beforeAll(async () => {
    const parsed = new URL(url!);
    if (parsed.hostname !== '127.0.0.1' || parsed.port !== '5441' || parsed.pathname !== '/postgres') throw new Error('Dedicated local gallery test container required');
    admin = postgres(url!, { max: 1, onnotice: () => {} });
    await admin.unsafe(`CREATE SCHEMA ${schema}`);
    db = postgres(url!, { max: 1, connection: { search_path: schema }, onnotice: () => {} });
    const run = (sql: { unsafe: typeof db.unsafe }) => async (text: string, params: unknown[] = []) => {
      let n = 0;
      return sql.unsafe(text.replace(/\?/g, () => `$${++n}`), params as never[]);
    };
    connection.query.mockImplementation(run(db));
    connection.withTransaction.mockImplementation((fn: (q: ReturnType<typeof run>) => unknown) => db.begin(tx => fn(run(tx as unknown as typeof db)) as never));
    await db.unsafe(`CREATE TABLE app_users (id BIGINT PRIMARY KEY, wca_id TEXT, display_name TEXT,
      is_admin BOOLEAN DEFAULT FALSE, public_intro TEXT, public_intro_image_ids JSONB DEFAULT '[]', show_in_member_list BOOLEAN DEFAULT TRUE);
      CREATE TABLE effective_memberships (wca_id TEXT PRIMARY KEY, expires_at TIMESTAMPTZ);
      CREATE TABLE article_image (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data BYTEA NOT NULL, mime TEXT NOT NULL, width INTEGER, height INTEGER,
        size_bytes INTEGER NOT NULL, owner_wca_id TEXT NOT NULL);`);
    await db.unsafe(`INSERT INTO app_users (id,wca_id,display_name,public_intro_image_ids) VALUES (1,'2000TEST01','Owner','[1]');
      INSERT INTO article_image(data,mime,size_bytes,owner_wca_id) VALUES ('photo','image/png',5,'2000TEST01'),('article','image/png',7,'2000TEST01');`);
    await db.unsafe(readFileSync(new URL('../migrations/0301_gallery_publication.sql', import.meta.url), 'utf8'));
    expect(await db.unsafe('SELECT gallery_status FROM article_image ORDER BY id')).toEqual([
      { gallery_status: 'private' }, { gallery_status: null },
    ]);
  });
  beforeEach(async () => {
    await db.unsafe(`TRUNCATE app_users, article_image, effective_memberships RESTART IDENTITY;
      INSERT INTO app_users (id,wca_id,display_name,public_intro_image_ids,show_in_member_list) VALUES (1,'2000TEST01','Owner','[1]',FALSE);
      INSERT INTO effective_memberships VALUES ('2000TEST01',NULL);
      INSERT INTO article_image(data,mime,size_bytes,owner_wca_id,gallery_status) VALUES
        ('photo','image/png',5,'2000TEST01','private'), ('article','image/png',7,'2000TEST01',NULL);`);
  });
  afterAll(async () => { await db?.end(); if (admin) { await admin.unsafe(`DROP SCHEMA ${schema} CASCADE`); await admin.end(); } });

  it('uploads privately before profile save and denies strangers/admins on originals and thumbnails', async () => {
    const uploaded = await request('/article/img/gallery', 'owner', 'POST', { mime: 'image/png', dataB64: Buffer.from('fixture').toString('base64') });
    expect(uploaded.status).toBe(200);
    const { id } = await uploaded.json();
    expect((await db.unsafe('SELECT gallery_status FROM article_image WHERE id=$1', [id]))[0].gallery_status).toBe('private');
    for (const path of [`/article/img/${id}`, '/article/img/1', '/article/img/1/thumb/512?v=1']) {
      for (const actor of [undefined, 'other', 'admin']) {
        const denied = await request(path, actor);
        expect(denied.status).toBe(404);
        expect(denied.headers.get('cache-control')).toBe('no-store');
      }
      expect((await request(path, 'owner')).status).toBe(200);
    }
    expect((await request('/article/img/2')).headers.get('cache-control')).toContain('immutable');
  });

  it('publishes only after an owner request and admin review, independently of homepage listing', async () => {
    expect((await visibility('public')).status).toBe(400);
    expect((await visibility('pending', 'other')).status).toBe(403);
    await db.unsafe("INSERT INTO effective_memberships VALUES ('2000TEST02',NULL)");
    expect((await visibility('pending', 'other')).status).toBe(409);
    expect((await visibility('private', 'other')).status).toBe(409);
    expect((await review('public')).status).toBe(409);
    expect((await visibility('pending')).status).toBe(200);
    expect((await request('/membership/gallery/review', 'owner')).status).toBe(403);
    expect((await request('/article/img/1', 'admin')).status).toBe(200);
    expect((await request('/article/img/1')).status).toBe(404);
    expect((await (await request('/membership/gallery')).json()).photos).toEqual([]);
    expect((await (await request('/membership/profile/2000TEST01')).json()).profile.imageIds).toEqual([]);
    expect((await review('public', 'owner')).status).toBe(403);
    expect((await review('public')).status).toBe(200);
    const photos = (await (await request('/membership/gallery')).json()).photos;
    expect(photos).toEqual([{ id: 1, memberName: 'Owner', wcaId: '2000TEST01' }]);
    expect((await (await request('/membership/profile/2000TEST01')).json()).profile.imageIds).toEqual([1]);
    const publicImage = await request('/article/img/1');
    expect(publicImage.status).toBe(200);
    expect(publicImage.headers.get('cache-control')).toBe('no-store');
  });

  it('withdraws requests, rejects stale decisions, and permits reapplying after a decline', async () => {
    expect((await visibility('pending')).status).toBe(200);
    expect((await visibility('private')).status).toBe(200);
    expect((await review('public')).status).toBe(409);
    expect((await visibility('pending')).status).toBe(200);
    expect((await review('rejected')).status).toBe(200);
    expect((await request('/article/img/1', 'admin')).status).toBe(404);
    expect((await visibility('pending')).status).toBe(200);
    expect((await review('public')).status).toBe(200);
    expect((await visibility('private')).status).toBe(200);
    expect((await request('/article/img/1')).status).toBe(404);
  });

  it('removes approval on deletion, makes legacy uploads private, and prevents republishing by reattachment', async () => {
    await visibility('pending'); await review('public');
    expect((await save([])).status).toBe(200);
    expect((await request('/article/img/1')).status).toBe(404);
    expect((await save([1, 2])).status).toBe(200);
    expect(await db.unsafe('SELECT gallery_status FROM article_image ORDER BY id')).toEqual([
      { gallery_status: 'private' }, { gallery_status: 'private' },
    ]);
    expect((await request('/article/img/2')).status).toBe(404);
    expect((await (await request('/membership/gallery')).json()).photos).toEqual([]);
  });

  it('hides expired and detached public photos while retaining owner access', async () => {
    await visibility('pending'); await review('public');
    await db.unsafe("UPDATE effective_memberships SET expires_at='2000-01-01'");
    expect((await request('/article/img/1')).status).toBe(404);
    expect((await request('/article/img/1', 'owner')).status).toBe(200);
    expect((await (await request('/membership/gallery')).json()).photos).toEqual([]);
    expect((await visibility('private')).status).toBe(200);
    expect((await visibility('pending')).status).toBe(403);
    await db.unsafe("UPDATE effective_memberships SET expires_at=NULL; UPDATE article_image SET gallery_status='public'; UPDATE app_users SET public_intro_image_ids='[]'");
    expect((await request('/article/img/1')).status).toBe(404);
  });
});
