CREATE TABLE workspace_payroll_rates (
  user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  effective_from DATE NOT NULL,
  ends_on DATE CHECK (ends_on >= effective_from),
  daily_rate_cents INTEGER CHECK (daily_rate_cents BETWEEN 1 AND 100000000),
  PRIMARY KEY (user_id, effective_from)
);

CREATE TABLE workspace_payroll_attendance (
  user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  work_date DATE NOT NULL,
  half_days SMALLINT NOT NULL CHECK (half_days IN (1, 2)),
  daily_rate_cents INTEGER NOT NULL CHECK (daily_rate_cents BETWEEN 1 AND 100000000),
  approved BOOLEAN NOT NULL,
  version INTEGER GENERATED BY DEFAULT AS IDENTITY CHECK (version > 0),
  PRIMARY KEY (user_id, work_date)
);

CREATE TABLE workspace_payroll_payments (
  user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
  work_month DATE NOT NULL CHECK (EXTRACT(DAY FROM work_month) = 1),
  total_cents BIGINT NOT NULL CHECK (total_cents > 0),
  paid_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (user_id, work_month)
);

CREATE INDEX workspace_project_tasks_payroll ON workspace_project_tasks(user_id, accepted_at)
  WHERE status = 'accepted';
