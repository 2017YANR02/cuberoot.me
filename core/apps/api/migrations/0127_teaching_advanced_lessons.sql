-- CFOP 之后的可维护课程池。公开读取，只有管理员可以新增、编辑、排序和删除。
CREATE TABLE teaching_advanced_lessons (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  track           VARCHAR(3)   NOT NULL CHECK (track IN ('333', '222')),
  position        INTEGER      NOT NULL DEFAULT 0 CHECK (position >= 0),
  title_zh        VARCHAR(200) NOT NULL,
  title_en        VARCHAR(200) NOT NULL,
  description_zh  TEXT         NOT NULL DEFAULT '',
  description_en  TEXT         NOT NULL DEFAULT '',
  minutes         SMALLINT     NOT NULL DEFAULT 5 CHECK (minutes BETWEEN 1 AND 60),
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CHECK (length(trim(title_zh)) > 0),
  CHECK (length(trim(title_en)) > 0)
);

CREATE INDEX idx_teaching_advanced_track_position
  ON teaching_advanced_lessons(track, position, id);
CREATE TRIGGER teaching_advanced_lessons_updated_at BEFORE UPDATE ON teaching_advanced_lessons
  FOR EACH ROW EXECUTE FUNCTION trg_set_updated_at();

