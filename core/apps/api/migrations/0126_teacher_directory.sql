-- 公开的魔方老师与培训机构名录。登录用户可维护自己的条目，管理员可维护全部条目。
CREATE TABLE teacher_directory_entries (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind             VARCHAR(16)  NOT NULL CHECK (kind IN ('teacher', 'organization')),
  name_zh          VARCHAR(160) NOT NULL DEFAULT '',
  name_en          VARCHAR(160) NOT NULL DEFAULT '',
  location_zh      VARCHAR(160) NOT NULL DEFAULT '',
  location_en      VARCHAR(160) NOT NULL DEFAULT '',
  description_zh   TEXT         NOT NULL DEFAULT '',
  description_en   TEXT         NOT NULL DEFAULT '',
  specialties_zh  JSONB        NOT NULL DEFAULT '[]'::jsonb,
  specialties_en  JSONB        NOT NULL DEFAULT '[]'::jsonb,
  teaching_mode    VARCHAR(16)  NOT NULL DEFAULT 'both'
                                CHECK (teaching_mode IN ('online', 'in_person', 'both')),
  contact          VARCHAR(300) NOT NULL DEFAULT '',
  website          TEXT         NOT NULL DEFAULT '',
  wca_id           VARCHAR(20),
  is_curated       BOOLEAN      NOT NULL DEFAULT FALSE,
  owner_key        VARCHAR(20)  NOT NULL,
  owner_name       VARCHAR(200) NOT NULL,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CHECK (name_zh <> '' OR name_en <> ''),
  CHECK (description_zh <> '' OR description_en <> ''),
  CHECK (contact <> '' OR website <> ''),
  CHECK (jsonb_typeof(specialties_zh) = 'array'),
  CHECK (jsonb_typeof(specialties_en) = 'array'),
  CHECK (wca_id IS NULL OR wca_id ~ '^[0-9]{4}[A-Z]{4}[0-9]{2}$')
);

CREATE INDEX idx_teacher_directory_kind_created
  ON teacher_directory_entries(kind, created_at, id);
CREATE INDEX idx_teacher_directory_owner
  ON teacher_directory_entries(owner_key, updated_at DESC);
CREATE TRIGGER teacher_directory_updated_at BEFORE UPDATE ON teacher_directory_entries
  FOR EACH ROW EXECUTE FUNCTION trg_set_updated_at();

