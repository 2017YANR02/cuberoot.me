CREATE TABLE forum_videos (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id      BIGINT REFERENCES forum_posts(id) ON DELETE CASCADE,
  owner_id     VARCHAR(32) NOT NULL,
  public_token VARCHAR(36) NOT NULL UNIQUE,
  storage_key  VARCHAR(80) NOT NULL UNIQUE,
  mime         VARCHAR(40) NOT NULL
                 CHECK (mime IN ('video/mp4', 'video/webm', 'video/quicktime')),
  size_bytes   BIGINT NOT NULL CHECK (size_bytes BETWEEN 1 AND 209715200),
  duration_ms  INT NOT NULL CHECK (duration_ms > 0),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  attached_at  TIMESTAMPTZ
);

CREATE INDEX idx_forum_videos_owner_created
  ON forum_videos(owner_id, created_at DESC);
CREATE INDEX idx_forum_videos_unbound_created
  ON forum_videos(created_at) WHERE post_id IS NULL;
CREATE UNIQUE INDEX idx_forum_videos_post
  ON forum_videos(post_id) WHERE post_id IS NOT NULL;
