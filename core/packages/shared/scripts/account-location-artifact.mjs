import { readFile, writeFile } from 'node:fs/promises';

/** Build-only entry: the shared package owns writes to its generated source. */
export async function writeAccountLocationRequirements(requirements, { check = false } = {}) {
  const destination = new URL('../src/data/account_location_requirements.ts', import.meta.url);
  const source = '// Generated by client/scripts/build-account-locations.mjs; do not edit.\n'
    + 'export const ACCOUNT_LOCATION_REQUIREMENTS: Readonly<Record<string, Readonly<Record<string, boolean>>>> = '
    + JSON.stringify(requirements, null, 2) + ';\n';
  if (check) {
    if (await readFile(destination, 'utf8') !== source) throw new Error('account location requirements are stale');
  } else {
    await writeFile(destination, source);
  }
}
