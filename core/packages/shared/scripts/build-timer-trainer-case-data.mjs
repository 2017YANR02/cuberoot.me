import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(packageRoot, 'src/timer/trainer-case-data.generated.ts');
const args = new Set(process.argv.slice(2));
const write = args.has('--write');
const check = args.has('--check');

if (write === check || args.size !== 1) {
  throw new Error('usage: node scripts/build-timer-trainer-case-data.mjs (--write | --check)');
}

function readMap(name) {
  const value = JSON.parse(readFileSync(resolve(packageRoot, `data/${name}.json`), 'utf8'));
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${name}.json must contain an object`);
  }
  return value;
}

const ollMap = readMap('oll');
const pllMap = readMap('pll');
const zbllMap = readMap('zbll');

const oll = Object.entries(ollMap).map(([id, item]) => {
  if (!item || typeof item.name !== 'string' || typeof item.group !== 'string'
      || typeof item.alg !== 'string' || item.alg.length === 0) {
    throw new Error(`oll.json has an invalid case: ${id}`);
  }
  return [id, item.name, item.group, item.alg];
});
const pll = Object.entries(pllMap).map(([id, item]) => {
  if (!item || typeof item.noAuf !== 'string' || item.noAuf.length === 0) {
    throw new Error(`pll.json has an invalid case: ${id}`);
  }
  return [id, item.noAuf];
});
const zbll = Object.entries(zbllMap).map(([sourceId, item]) => {
  const first = item?.algs?.[0];
  if (typeof item?.key !== 'string' || typeof first !== 'string' || first.length === 0) {
    throw new Error(`zbll.json has an invalid case: ${sourceId}`);
  }
  return [item.key || sourceId, first];
});

const expectedCounts = { oll: 57, pll: 21, zbll: 472 };
for (const [name, rows] of Object.entries({ oll, pll, zbll })) {
  if (rows.length !== expectedCounts[name]) {
    throw new Error(`${name}.json case count changed: expected ${expectedCounts[name]}, got ${rows.length}`);
  }
}

const generated = [
  '/**',
  ' * Generated by scripts/build-timer-trainer-case-data.mjs from the canonical',
  ' * data/{oll,pll,zbll}.json maps. Do not edit this projection by hand.',
  ' */',
  `export const TIMER_OLL_CASE_DATA: ReadonlyArray<readonly [string, string, string, string]> = ${JSON.stringify(oll)};`,
  `export const TIMER_PLL_CASE_DATA: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(pll)};`,
  `export const TIMER_ZBLL_CASE_DATA: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(zbll)};`,
  '',
].join('\n');

if (write) {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${outputPath}`);
} else {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    throw new Error('trainer-case-data.generated.ts is stale; rerun with --write');
  }
  console.log('trainer-case-data.generated.ts is current');
}
