// The little fingertip rolls past the beveled cubie corner near the end of its stroke.
const pinkyHandoff = [[80, 0, 0], [82, .004, .008], [83, .017, 0], [84, 0, 0]];

export function lowerHookPose(name: 'pinky' | 'ring', degrees: number, relay: boolean,
  reach: number, decay: number, home: number[]) {
  const second = relay && name === 'ring';
  const angle = Math.max(0, Math.min(90, degrees - (second ? 90 : 0)));
  const pose = sampleFingerPose(name === 'pinky' ? pinky : ring, angle);
  // The next finger seats during the first quarter. As soon as it drives,
  // the little finger lets the next corner through on its way back to rest.
  const t = second ? Math.min(1, degrees / 90)
    : name === 'pinky' ? 1 - Math.min(1, Math.max(0, degrees - 90) / 50) : 1;
  const weight = t * t * (3 - 2 * t) * reach * decay;
  const result = home.map((v, i) => v + (pose[i] - v) * weight);
  if (second && degrees > 72 && degrees < 102) {
    const flex = sampleFingerPose(ringHandoff, degrees);
    for (let i = 0; i < flex.length; i++) result[i] += flex[i] * reach * decay;
  } else if (relay && name === 'pinky' && degrees > 80 && degrees < 84) {
    const [mcp, pip] = sampleFingerPose(pinkyHandoff, degrees);
    result[0] += mcp * reach * decay;
    result[1] += pip * reach * decay;
  }
  return result;
}
