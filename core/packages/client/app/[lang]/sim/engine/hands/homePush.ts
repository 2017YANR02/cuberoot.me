const profiles = {
  index: { drive: indexDrive, approach: indexApproach, release: indexRelease },
  ring: { drive: ringDrive, approach: ringApproach, release: ringRelease },
};

const fourProfiles = {
  index: { drive: evenIndexDrive, approach: evenIndexApproach, release: indexRelease },
  ring: { drive: fourRingDrive, approach: ringApproach, release: ringRelease },
};

const pocketProfiles = { ...fourProfiles, ring: { ...fourProfiles.ring, drive: pocketRingDrive } };

export function homePushPose(finger: 'index' | 'ring', degrees: number, reach: number, decay: number, home: number[], order = 3) {
  const profile = (order === 2 ? pocketProfiles : order === 4 ? fourProfiles : profiles)[finger];
  const sample = sampleFingerPose(profile.drive, degrees);
  const weight = reach * decay;
  const clearance = decay < 1 ? profile.release : profile.approach;
  return sample.map((value, i) => {
    const rest = home[i] ?? 0;
    return rest + (value - rest) * weight + clearance[i] * 4 * weight * (1 - weight);
  });
}
