// After the nail clears the sticker, curl the interphalangeal joints to shorten
// the finger, then extend them as the MCP returns along its own flexion plane.
// Cubic control offsets (radians from the straight chord, same columns as FRAMES).
const withdrawalLead = [0, 1.047, -.187, 0, -.031, -.015, .002, -.006];
const withdrawalTrail = [.001, -.100, .683, .002, -.027, -.417, .066, -.013];

export function frontIndexReturn(pose: FingerCurl, departure: number[], t: number): number[] {
  const home = [pose.curl[0], pose.curl[1], Math.max(.03, pose.curl[2]), pose.splay, 0, 0, 0, 0];
  const u = 1 - t;
  return departure.map((start, k) => {
    const arc = 3 * u * t * (u * withdrawalLead[k] + t * withdrawalTrail[k]);
    return u * start + t * home[k] + arc;
  });
}
