export function mixedGripPose(style: MixedPush, reach: number, degrees: number, release: number, order = 3): number[] {
  const nailPath = order === 3 && isSliceNail(style)
    ? (style === 'sliceNailDouble' ? sliceNailDouble : sliceNail) : null;
  const path = nailPath ?? (style === 'thumbLift' ? thumbLift : legacySliceNail);
  // A drag that snaps back to zero retracts through its clearance waypoints.
  if ((degrees < 4 || style === 'sliceNailDouble' && Math.abs(degrees - 90) < 4) && release > 0) {
    const withdrawing = sampleFingerPose(path.approach, reach * (1 - release));
    const turn = sampleFingerPose(path.turn, degrees);
    return withdrawing.map((value, i) => value + reach * (1 - release) * (turn[i] - path.turn[0][i + 1]));
  }
  if (nailPath && release > 0 && degrees >= (style === 'sliceNailDouble' ? 90 : 0) + SLICE_NAIL_RETURN_DEG) {
    const retreat = sampleFingerPose(nailPath.release, release);
    const last = path.turn.at(-1)!;
    const driven = sampleFingerPose(path.turn, degrees);
    return retreat.map((value, i) => value + (driven[i] - last[i + 1]) * (1 - release));
  }
  const approach = sampleFingerPose(path.approach, reach);
  const turn = sampleFingerPose(path.turn, degrees);
  const start = path.turn[0], rest = path.approach[0];
  return approach.map((value, i) => {
    const moving = value + reach * (turn[i] - start[i + 1]);
    return moving + release * (rest[i + 1] - moving);
  });
}
