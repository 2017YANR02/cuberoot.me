function sampleStroke(rows: FingerPoseRows, degrees: number, decay: number): number[] {
  const pose = sampleFingerPose(rows, degrees);
  if (decay === 1) return pose;
  return pose.map((value, i) => rows[0][i + 1] + (value - rows[0][i + 1]) * decay);
}

export function applyPocketFaceStroke(stroke: PocketFaceStroke, degrees: number, decay: number, reach: number,
  mirror: number, fingers: Record<FingerName, FingerJoints>, palm: { x: number; y: number; z: number },
  elbow: { x: number; y: number; z: number }): void {
  if (stroke.palm) {
    const [x, y, z] = sampleStroke(stroke.palm, degrees, decay);
    palm.x += x * reach * mirror;
    palm.y += y * reach;
    palm.z += z * reach;
    elbow.x += x * reach * mirror;
    elbow.y += y * reach;
    elbow.z += z * reach;
  }
  for (const name of Object.keys(stroke.fingers) as FingerName[]) {
    applyPocketFingerPose(fingers[name], sampleStroke(stroke.fingers[name]!, degrees, decay), reach, mirror);
  }
}
