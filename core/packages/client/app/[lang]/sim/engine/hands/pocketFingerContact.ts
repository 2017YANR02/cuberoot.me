export function seatPocketFinger(finger: FingerJoints, path: FingerPoseRows, degrees: number, weight: number, mirrorSplay = 1): void {
  applyPocketFingerPose(finger, sampleFingerPose(path, degrees), weight, mirrorSplay);
}

export function applyPocketFingerPose(finger: FingerJoints, pose: readonly number[], weight: number, mirrorSplay: number): void {
  const [flex, splay, hinge, roll = 0, distal = 0, palmX = 0, palmY = 0, palmZ = 0] = pose;
  if (finger.meta && (palmX || palmY || palmZ)) {
    finger.meta.rotateX(palmX * weight * mirrorSplay);
    finger.meta.rotateY(palmY * weight);
    finger.meta.rotateZ(palmZ * weight * mirrorSplay);
  }
  finger.root.rotateY(flex * weight);
  finger.root.rotateZ(splay * weight * mirrorSplay);
  if (roll) finger.root.rotateX(roll * weight * mirrorSplay);
  finger.mid.rotateY(hinge * weight);
  if (distal) finger.tip.rotateY(distal * weight);
}
