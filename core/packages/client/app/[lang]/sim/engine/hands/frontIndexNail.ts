export function frontIndexNailPose(degrees: number, reach: number, decay: number) {
  if (decay === 0) return reach < 1 ? sampleFingerPose(approach, reach) : sampleFingerPose(stroke, degrees);

  // A drop snaps the layer to the nearest quarter. Finish the last visible
  // fraction of the stroke before withdrawing around the seated corner.
  const seated = degrees >= 45 ? 90 : 0;
  const remaining = Math.abs(seated - degrees) / 90;
  if (remaining > 0 && 1 - decay < remaining) {
    return sampleFingerPose(stroke, degrees + (seated - degrees) * (1 - decay) / remaining);
  }
  return sampleFingerPose(seated ? withdrawal : approach, decay / (1 - remaining));
}
