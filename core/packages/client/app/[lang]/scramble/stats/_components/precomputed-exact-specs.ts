/** Small published mathematical tables and bounded, independently checked witnesses.
 * Generated by scripts/export-exact-puzzle-distributions.mts; no solver is imported here. */
interface ExactDataset {
  total: number;
  godsNumber: number;
  histogram: number[];
  examples: Array<{ depth: number; scramble: string; solution: string }>;
  metric: TrText;
  scope: TrText;
  examplesPerDepthLimit?: number;
  deepestExamplesComplete?: boolean;
  quotient?: boolean;
  physicalStatesPerCoordinate?: number;
  provenance?: { generatedAt: string; reportSha256: string };
}
const datasets = (data as { schemaVersion: number; puzzles: Record<string, ExactDataset> }).puzzles;
const downloadManifest = downloads as { schemaVersion: number; inventorySha256?: string; puzzles: Record<string, ExactDownloads> };
const published = publication.published as { inventorySha256: string } | null;
const downloadsAvailable = process.env.NODE_ENV === 'development'
  || Boolean(published && published.inventorySha256 === downloadManifest.inventorySha256);
const downloadAssets = Object.fromEntries(Object.entries(downloadManifest.puzzles).map(([event, assets]) => {
  // Keep development SSR and hydration on the same local URL. Production uses
  // the shared static-origin resolver and never bundles the corpus in Next.
  const asset = (value: NonNullable<ExactDownloads['allStates']>) => ({ ...value,
    url: process.env.NODE_ENV === 'development' ? value.url : statsUrl(value.url) });
  return [event, { allStates: assets.allStates && asset(assets.allStates),
    byDepth: Object.fromEntries(Object.entries(assets.byDepth ?? {}).map(([depth, value]) => [depth, asset(value)])) }];
}));

export const PRECOMPUTED_EXACT_SUMMARIES = Object.fromEntries(Object.entries(datasets)
  .map(([event, dataset]) => [event, { total: dataset.total, godsNumber: dataset.godsNumber, metric: dataset.metric, quotient: dataset.quotient, subgoal: event.startsWith('roux-') || dataset.quotient }]));

interface ExactPuzzleCatalogEntry {
  id: string;
  zh: string;
  en: string;
  icon: string;
  description?: string;
  previewEvent?: string;
  previewLabel?: TrText;
  disableExampleLink?: boolean;
  simulatorEvent?: string;
}

export const PRECOMPUTED_EXACT_PUZZLES = Object.keys(datasets).map(event => {
  if (event === 'ufo') return {
    id: event, zh: '项目 UFO 模型', en: 'Project UFO model', icon: 'unofficial-ufo',
    disableExampleLink: true,
    previewLabel: { zh: '三球模型图示；与实体 UFO 的对应关系尚未核验。', en: 'Three-ball model preview; correspondence with a physical UFO remains unverified.' },
  } satisfies ExactPuzzleCatalogEntry;
  if (event === 'pyraminx_duo') {
    const puzzle = EVENTS.find(candidate => candidate.id === event)!;
    return { id: event, zh: puzzle.nameZh, en: puzzle.nameEn, icon: puzzle.icon!, simulatorEvent: event } satisfies ExactPuzzleCatalogEntry;
  }
  if (event.startsWith('roux-')) return {
    id: event,
    zh: event === 'roux-eodm' ? '桥式 EO+DM' : `桥式 ${event.slice(5).toUpperCase().replaceAll('-', ' ')} 准备目标`,
    en: event === 'roux-eodm' ? 'Roux EO+DM' : `Roux ${event.slice(5).toUpperCase().replaceAll('-', ' ')} setup target`,
    icon: 'event-333', previewEvent: '333', disableExampleLink: true,
  } satisfies ExactPuzzleCatalogEntry;
  if (event === 'htr-dr' || event === 'fr-htr') return {
    id: event, zh: event === 'htr-dr' ? 'DR → HTR' : 'HTR → FR（固定 UD）',
    en: event === 'htr-dr' ? 'DR → HTR' : 'HTR → FR (fixed UD)',
    icon: 'event-333', previewEvent: '333', disableExampleLink: true,
  } satisfies ExactPuzzleCatalogEntry;
  if (event === 'pyram-tips') return {
    id: event, zh: `${eventDisplayName('pyram', true)}（含小尖）`,
    en: `${eventDisplayName('pyram', false)} (including tips)`, icon: 'event-pyram',
    previewEvent: 'pyram', simulatorEvent: 'pyraminx',
  } satisfies ExactPuzzleCatalogEntry;
  // csTimer's half / lsemu identifiers describe restricted 3×3 move groups;
  // they are not separate physical puzzles or general-purpose solver events.
  if (event === 'half' || event === 'lsemu' || event === 'lsemu-qtm') return {
    id: event,
    zh: `${eventDisplayName('333', true)}（${event === 'half' ? '仅半转' : '仅 U、M'}）${event.endsWith('-qtm') ? ' QSTM' : ''}`,
    en: `${eventDisplayName('333', false)} (${event === 'half' ? 'half turns only' : 'U, M only'})${event.endsWith('-qtm') ? ' QSTM' : ''}`,
    icon: 'event-333', previewEvent: '333', simulatorEvent: '3',
  } satisfies ExactPuzzleCatalogEntry;
  if (event === 'skewb') return {
    id: event, zh: eventDisplayName(event, true), en: eventDisplayName(event, false), icon: 'event-skewb',
  } satisfies ExactPuzzleCatalogEntry;
  const cstimer = CSTIMER_EVENTS.find(candidate => candidate.id === (event === 'dino-mirror' ? 'dino' : event));
  if (event === 'dino-mirror' && cstimer) return {
    id: event, zh: `${cstimer.zh}（接受镜像配色）`, en: `${cstimer.en} (mirror colors accepted)`,
    icon: cstimer.iconClass ?? '', previewEvent: 'dino', disableExampleLink: true,
  } satisfies ExactPuzzleCatalogEntry;
  if (cstimer) return {
    id: event, zh: cstimer.zh, en: cstimer.en, icon: cstimer.iconClass ?? '',
  } satisfies ExactPuzzleCatalogEntry;
  const isPyramorphix = event === 'pyramorphix' || event === 'pyramorphix-qtm';
  const puzzle = PG_PUZZLES.find(candidate => candidate.id === (isPyramorphix ? 'pyramorphix' : event));
  if (!puzzle) throw new Error(`Missing exact-distribution puzzle catalog entry: ${event}`);
  if (isPyramorphix) return {
    id: event, zh: `${puzzle.zh} ${event.endsWith('-qtm') ? 'QTM' : 'HTM'}`,
    en: `${puzzle.en} ${event.endsWith('-qtm') ? 'QTM' : 'HTM'}`, icon: puzzle.icon,
    previewEvent: '222', disableExampleLink: true,
    previewLabel: { zh: '图示为二阶角块坐标，不代表魔金的实际形状。', en: 'The preview shows 2×2 corner coordinates, not the physical Pyramorphix shape.' },
  } satisfies ExactPuzzleCatalogEntry;
  return { id: event, zh: puzzle.zh, en: puzzle.en, icon: puzzle.icon, description: puzzle.def } satisfies ExactPuzzleCatalogEntry;
}) as ExactPuzzleCatalogEntry[];

export const PRECOMPUTED_EXACT_SPECS: Record<string, EnumSpec> = Object.fromEntries(
  PRECOMPUTED_EXACT_PUZZLES.map(puzzle => {
    const dataset = datasets[puzzle.id];
    const counts = Object.fromEntries(dataset.histogram.map((count, depth) => [String(depth), count]));
    const examples: Record<number, string[]> = {};
    const solutions = new Map<string, string>();
    for (const example of dataset.examples) {
      (examples[example.depth] ??= []).push(example.scramble);
      solutions.set(example.scramble, example.solution);
    }
    const total = dataset.total.toLocaleString('en-US');
    const limit = dataset.examplesPerDepthLimit ?? Math.max(...Object.values(examples).map(items => items.length));
    const deepest = dataset.histogram[dataset.godsNumber];
    const subgroup = puzzle.id === 'half' || puzzle.id.startsWith('lsemu');
    const subgoal = puzzle.id.startsWith('roux-') || dataset.quotient;
    const spec: EnumSpec = {
      event: puzzle.id,
      color: 'var(--accent)',
      seriesName: { zh: puzzle.zh, en: puzzle.en },
      spaceLabel: dataset.quotient
        ? { zh: `精确陪集分布 · ${total} 个陪集`, en: `Exact coset distribution · ${total} cosets` }
        : subgoal
        ? { zh: `LSE 子阶段精确分布 · ${total} 态`, en: `Exact LSE sub-goal distribution · ${total} states` }
        : subgroup
        ? { zh: `子群精确分布 · ${total} 态`, en: `Exact subgroup distribution · ${total} states` }
        : puzzle.id === 'ufo'
        ? { zh: `项目模型精确分布 · ${total} 态`, en: `Exact project-model distribution · ${total} states` }
        : { zh: `全空间精确分布 · ${total} 态`, en: `Exact full-space distribution · ${total} states` },
      moveUnitLabel: dataset.metric,
      meta: () => ({
        zh: `${dataset.scope.zh} ${dataset.deepestExamplesComplete
          ? `最深档 ${deepest} 态已列全，其余档最多 ${limit} 条预计算示例。`
          : `每档最多 ${limit} 条预计算示例。`}`,
        en: `${dataset.scope.en} ${dataset.deepestExamplesComplete
          ? `All ${deepest} deepest states are listed, with up to ${limit} precomputed examples at other depths.`
          : `Up to ${limit} precomputed examples per depth.`}`,
      }),
      lengthNote: {
        zh: '暂无打乱长度语料；完整最优步数分布见「难度」。',
        en: 'No scramble-length corpus is available; see Difficulty for the complete optimal-distance distribution.',
      },
      puzzleDescription: puzzle.description,
      previewEvent: puzzle.previewEvent,
      previewLabel: puzzle.previewLabel,
      exampleLink: puzzle.disableExampleLink ? null : (puzzle.description || puzzle.simulatorEvent) ? {
        href: scramble => `/sim?${new URLSearchParams({ puzzle: puzzle.simulatorEvent ?? puzzle.id, setup: scramble, alg: solutions.get(scramble) ?? '' })}`,
        label: { zh: '在模拟器中查看解法', en: 'View solution in simulator' },
      } : undefined,
      solutionForScramble: scramble => solutions.get(scramble),
      solvedLabel: subgoal ? { zh: '已达目标', en: 'Goal reached' } : undefined,
      subgoal,
      quotient: dataset.quotient,
      downloads: downloadsAvailable ? downloadAssets[puzzle.id] : undefined,
      downloadExamples: {
        label: { zh: '示例及最优解 (CSV)', en: 'Examples and optimal solutions (CSV)' },
        run: () => downloadCsv(`${puzzle.id}_examples.csv`, 'optimal_length,scramble,solution',
          dataset.examples.map(example => `${example.depth},${example.scramble},${example.solution}`)),
      },
      source: {
        kind: 'js', counts, examplesByLength: () => examples, downloadBin: null,
        downloadAllLabel: { zh: '下载完整分布 (CSV)', en: 'Download complete distribution (CSV)' },
        downloadAll: () => downloadCsv(`${puzzle.id}_distribution.csv`,
          dataset.quotient ? 'depth,count,physical_count,probability' : 'depth,count,probability',
          dataset.histogram.map((count, depth) => dataset.quotient
            ? `${depth},${count},${count * dataset.physicalStatesPerCoordinate!},${count / dataset.total}`
            : `${depth},${count},${count / dataset.total}`)),
      },
    };
    return [puzzle.id, spec];
  }),
);
