import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { SQ1_TOKEN_RE, canonicalSq1Alg, parseSq1Tokens } from '@cuberoot/shared/sq1-notation';

const SOURCE_URL = 'https://docs.google.com/spreadsheets/d/1VQNYNwdOLqqBkacHcfYtEBst22FOVhH9EAhTOYOZTgo/edit';
const EXPECTED_UNUSED = ['Ga/Gd', 'Ga/Jb', 'Gb/Gc', 'Gb/Jb'];
const EXPECTED_M_DB = '(1, 0) / (-3, 0) / (3, 0) / (-1, 2) / (0, 3) / (-3, -3) / (4, -2) / (-1, 0)';
const DATA_URL = new URL('../../data/sq1-pbl/cases.json', import.meta.url);
const OUTPUT_URL = new URL('../../../server/migrations/0140_sq1_pbl.sql', import.meta.url);

function fail(message) {
  throw new Error(`SQ1 PBL migration: ${message}`);
}

function noteFor(item) {
  const en = [];
  const zh = [];
  if (item.recommendation?.algorithm) {
    en.push(`Source mnemonic: ${item.recommendation.algorithm}`);
    zh.push(`原表助记：${item.recommendation.algorithm}`);
  }
  if (!item.used) {
    en.push('The source keeps this double-misalignment case but excludes it from its recommended slicer lists.');
    zh.push('原表保留此双错位情况，但未将其列入推荐切数表。');
  }
  return en.length ? { en: en.join('\n'), zh: zh.join('\n') } : undefined;
}

function assertStrictSq1(key, solution) {
  const matcher = new RegExp(SQ1_TOKEN_RE.source, 'g');
  let cursor = 0;
  let match;
  while ((match = matcher.exec(solution)) !== null) {
    if (solution.slice(cursor, match.index).trim()) fail(`${key} contains unsupported notation`);
    cursor = matcher.lastIndex;
  }
  if (solution.slice(cursor).trim()) fail(`${key} contains unsupported notation`);
}

function buildRows(document) {
  if (document.schemaVersion !== 1) fail(`unsupported cases schema ${document.schemaVersion}`);
  if (document.source?.documentUrl !== SOURCE_URL) fail('unexpected source document');
  if (!Array.isArray(document.cases) || document.cases.length !== 968) {
    fail(`expected 968 source cases, got ${document.cases?.length ?? 'invalid'}`);
  }

  const keys = new Set();
  const unused = [];
  const rows = [];
  let solved = 0;

  for (const item of document.cases) {
    if (!item || typeof item.key !== 'string' || keys.has(item.key)) fail(`invalid or duplicate key ${item?.key}`);
    keys.add(item.key);
    if (item.key === '-/-') {
      if (item.solution !== null || item.slices !== 0) fail('solved -/- row changed unexpectedly');
      solved += 1;
      continue;
    }

    if (typeof item.solution !== 'string' || !item.solution.trim()) fail(`${item.key} has no executable solution`);
    if (!item.used) unused.push(item.key);

    assertStrictSq1(item.key, item.solution);
    const alg = canonicalSq1Alg(item.solution);
    const tokens = parseSq1Tokens(item.solution);
    if (!alg || tokens.filter(token => token.kind === 'slice').length !== item.slices) {
      fail(`${item.key} has an invalid solution or slice count`);
    }
    const subgroup = `${item.shapePair === 'nP/nP' ? 'nP' : 'P'}/${item.top}`;
    const note = noteFor(item);
    rows.push({
      position: rows.length,
      name: item.key,
      subgroup,
      setup: '',
      sticker: {
        kind: 'raw',
        tag: 'sq1-pbl',
        attrs: {
          top: item.top,
          bottom: item.bottom,
          shapePair: item.shapePair,
          slices: String(item.slices),
          frequency: String(item.frequency),
          bucket: item.bucket,
          recommended: String(item.recommended),
          used: String(item.used),
        },
      },
      algs: [[{ alg, ...(note ? { note } : {}) }]],
    });
  }

  if (solved !== 1) fail(`expected one solved reference, got ${solved}`);
  if (rows.length !== 967) fail(`expected 967 formula cases, got ${rows.length}`);
  if (new Set(rows.map(row => row.algs[0][0].alg)).size !== 967) fail('formula solutions are not unique');
  if (JSON.stringify(unused.sort()) !== JSON.stringify([...EXPECTED_UNUSED].sort())) {
    fail(`unexpected unused cases: ${unused.join(', ')}`);
  }
  const mDb = rows.find(row => row.name === 'M/Db');
  if (mDb?.algs[0][0].alg !== EXPECTED_M_DB) fail('M/Db recovery no longer matches Standard Algs Data!T208');
  return rows;
}

function renderSql(document, rows) {
  const json = JSON.stringify(rows, null, 2);
  return `-- SQ1 PBL: import Daniel's complete executable PBL formula set.
-- Generated by packages/client/scripts/sq1-pbl/build-alg-migration.mjs.
-- Source: ${SOURCE_URL}
-- Workbook content digest: ${document.source.contentDigest}
-- The solved -/- reference is intentionally excluded; M/Db is recovered from Standard Algs Data!T208.

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM alg_cases WHERE puzzle = 'sq1' AND set_slug = 'pbl') THEN
    RAISE EXCEPTION 'SQ1 PBL cases already exist; use a new migration to update them without discarding user state';
  END IF;
END $$;

INSERT INTO alg_sets (puzzle, set_slug, source, scraped_at)
VALUES ('sq1', 'pbl', '${SOURCE_URL}', NOW())
ON CONFLICT (puzzle, set_slug) DO UPDATE
SET source = EXCLUDED.source, scraped_at = EXCLUDED.scraped_at;

WITH payload AS (
  SELECT $sq1_pbl_cases$${json}$sq1_pbl_cases$::jsonb AS value
), rows AS (
  SELECT item.*
  FROM payload,
  jsonb_to_recordset(payload.value) AS item(
    position INTEGER,
    name TEXT,
    subgroup TEXT,
    setup TEXT,
    sticker JSONB,
    algs JSONB
  )
)
INSERT INTO alg_cases (puzzle, set_slug, position, name, subgroup, setup, sticker, algs)
SELECT 'sq1', 'pbl', position, name, subgroup, setup, sticker, algs
FROM rows
ORDER BY position;

DO $$
DECLARE
  imported_count INTEGER;
  distinct_names INTEGER;
  nonempty_algs INTEGER;
BEGIN
  SELECT COUNT(*), COUNT(DISTINCT name),
    COUNT(*) FILTER (WHERE btrim(algs #>> '{0,0,alg}') <> '')
  INTO imported_count, distinct_names, nonempty_algs
  FROM alg_cases
  WHERE puzzle = 'sq1' AND set_slug = 'pbl';

  IF imported_count <> 967 OR distinct_names <> 967 OR nonempty_algs <> 967 THEN
    RAISE EXCEPTION 'SQ1 PBL import mismatch: rows %, names %, executable %',
      imported_count, distinct_names, nonempty_algs;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM alg_cases
    WHERE puzzle = 'sq1' AND set_slug = 'pbl'
      AND (position < 0 OR position > 966)
  ) THEN
    RAISE EXCEPTION 'SQ1 PBL positions are outside 0..966';
  END IF;
END $$;
`;
}

const document = JSON.parse(await readFile(DATA_URL, 'utf8'));
const output = renderSql(document, buildRows(document));
const mode = process.argv[2] ?? '--check';

if (mode === '--write') {
  await writeFile(OUTPUT_URL, output, 'utf8');
  console.log(`wrote ${fileURLToPath(OUTPUT_URL)}`);
} else if (mode === '--check') {
  const current = await readFile(OUTPUT_URL, 'utf8').catch(() => '');
  if (current !== output) fail('generated SQL is stale; run with --write');
  console.log('SQ1 PBL migration is current: 967 formula cases');
} else {
  fail(`unknown mode ${mode}`);
}
