import { readFile, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);

function option(name) {
  const index = args.indexOf(name);
  if (index === -1) return undefined;
  const value = args[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a value`);
  return value;
}

const inputArg = option('--input');
const outputArg = option('--output');
const write = args.includes('--write');
const check = args.includes('--check');
if (!inputArg || write === check) {
  throw new Error('Usage: node build-tnoodle-i18n.mjs --input <TNoodle i18n dir> (--write|--check) [--output <file>]');
}

const scriptDir = dirname(fileURLToPath(import.meta.url));
const inputDir = resolve(inputArg);
const outputPath = outputArg
  ? resolve(outputArg)
  : resolve(scriptDir, '../app/[lang]/scramble/gen/_tnoodle-i18n.ts');

function parseScalar(value, file, lineNumber) {
  const trimmed = value.trim();
  if (trimmed.startsWith("'") && trimmed.endsWith("'")) {
    return trimmed.slice(1, -1).replaceAll("''", "'");
  }
  if (trimmed.startsWith('"') && trimmed.endsWith('"')) {
    try {
      return JSON.parse(trimmed);
    } catch (error) {
      throw new Error(`${file}:${lineNumber}: invalid double-quoted YAML scalar: ${error.message}`);
    }
  }
  return trimmed;
}

function foldBlock(lines) {
  const paragraphs = [];
  let paragraph = [];
  for (const line of lines) {
    if (line === '') {
      if (paragraph.length > 0) paragraphs.push(paragraph.join(' '));
      paragraph = [];
    } else {
      paragraph.push(line.trim());
    }
  }
  if (paragraph.length > 0) paragraphs.push(paragraph.join(' '));
  return paragraphs.join('\n');
}

function parseFmcYaml(text, locale, file) {
  const lines = text.replaceAll('\r\n', '\n').split('\n');
  const localeIndex = lines.findIndex((line) => line === `${locale}:`);
  const fmcIndex = lines.findIndex((line, index) => index > localeIndex && line === '    fmc:');
  if (localeIndex === -1 || fmcIndex === -1) throw new Error(`${file}: missing ${locale}.fmc mapping`);

  const fmc = {};
  for (let index = fmcIndex + 1; index < lines.length;) {
    const line = lines[index];
    if (line !== '' && !line.startsWith('        ')) break;
    if (line.trim() === '' || line.trimStart().startsWith('#')) {
      index += 1;
      continue;
    }

    const match = /^ {8}([A-Za-z0-9_]+):(?:\s(.*))?$/.exec(line);
    if (!match) throw new Error(`${file}:${index + 1}: unsupported YAML in fmc mapping`);
    const [, key, rawValue = ''] = match;
    if (Object.hasOwn(fmc, key)) throw new Error(`${file}:${index + 1}: duplicate fmc.${key}`);

    if (/^[>|][-+]?$/.test(rawValue)) {
      const block = [];
      index += 1;
      while (index < lines.length && (lines[index] === '' || lines[index].startsWith('            '))) {
        block.push(lines[index] === '' ? '' : lines[index].slice(12));
        index += 1;
      }
      fmc[key] = rawValue.startsWith('>') ? foldBlock(block) : block.join('\n');
      continue;
    }

    fmc[key] = parseScalar(rawValue, file, index + 1);
    index += 1;
  }
  return fmc;
}

function render(data, locales, keys) {
  const localeType = locales.map((locale) => JSON.stringify(locale)).join(' | ');
  const interfaceLines = keys.map((key) => `    ${key}: string;`).join('\n');
  return `// Generated by core/packages/client/scripts/build-tnoodle-i18n.mjs from thewca/tnoodle i18n YAML.\n` +
    `// DO NOT EDIT BY HAND. Re-run the generator when TNoodle updates translations.\n\n` +
    `export type TnoodleLocale = ${localeType};\n\n` +
    `export const TNOODLE_LOCALES: readonly TnoodleLocale[] = ${JSON.stringify(locales)} as const;\n\n` +
    `export interface TnoodleTranslations {\n  fmc: {\n${interfaceLines}\n  };\n}\n\n` +
    `export const TNOODLE_I18N: Record<TnoodleLocale, TnoodleTranslations> = ${JSON.stringify(data, null, 2)};\n`;
}

if (!existsSync(inputDir)) throw new Error(`TNoodle i18n input directory does not exist: ${inputDir}`);
const files = (await readdir(inputDir, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && ['.yml', '.yaml'].includes(extname(entry.name)))
  .map((entry) => entry.name)
  .sort();
if (files.length === 0) throw new Error(`No TNoodle YAML files found in: ${inputDir}`);

const data = {};
let expectedKeys;
for (const file of files) {
  const locale = file.slice(0, -extname(file).length);
  const fmc = parseFmcYaml(await readFile(resolve(inputDir, file), 'utf8'), locale, file);
  const keys = Object.keys(fmc);
  if (!expectedKeys) expectedKeys = keys;
  const missing = expectedKeys.filter((key) => !keys.includes(key));
  const extra = keys.filter((key) => !expectedKeys.includes(key));
  if (missing.length > 0 || extra.length > 0) {
    throw new Error(`${file}: fmc key drift; missing [${missing.join(', ')}], extra [${extra.join(', ')}]`);
  }
  data[locale] = { fmc };
}

const generated = render(data, Object.keys(data).sort(), expectedKeys);
if (write) {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`Wrote ${outputPath} (${files.length} locales, ${expectedKeys.length} fmc keys)`);
} else {
  const current = await readFile(outputPath, 'utf8');
  if (current.replaceAll('\r\n', '\n') !== generated) {
    console.error(`TNoodle i18n snapshot is stale: ${outputPath}`);
    console.error(`Run with --write using the same --input directory.`);
    process.exitCode = 1;
  } else {
    console.log(`TNoodle i18n snapshot is current (${files.length} locales, ${expectedKeys.length} fmc keys)`);
  }
}
