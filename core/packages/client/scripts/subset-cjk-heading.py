#!/usr/bin/env python3
"""Generate self-hosted WenKai heading fonts and complete CJK fallback shards.

Run from packages/client:
    uv run --with fonttools --with brotli python scripts/subset-cjk-heading.py

Common headings share one subset per weight. Remaining source CJK glyphs are
split into 512-codepoint blocks with exact unicode-range declarations, so new
or dynamic headings never depend on the source-text collector for coverage.
Content hashes invalidate caches automatically. Source TTFs stay in core/.tmp.
"""
import os
import hashlib
from pathlib import Path
import re
import glob
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))            # packages/client
REPO = os.path.abspath(os.path.join(ROOT, "..", ".."))      # core workspace
FONTS_TMP = os.path.join(REPO, ".tmp", "fonts")
PUB_FONTS = os.path.join(ROOT, "public", "fonts")
# 衬线标题字重有 400 / 500(少量 600 由 500 近似);各出一档真字重,避免浏览器伪粗发糊。
REL = "https://github.com/lxgw/LxgwWenKai/releases/download/v1.522"
WEIGHTS = [
    (400, "LXGWWenKai-Regular.ttf", "lxgw-wenkai-heading.woff2"),
    (500, "LXGWWenKai-Medium.ttf",  "lxgw-wenkai-heading-500.woff2"),
]

CJK_PUNCT = "，。、；：？！“”‘’（）《》「」『』【】—…·～"


def keep(c: str) -> bool:
    o = ord(c)
    return (
        0x2E80 <= o <= 0x9FFF
        or 0xF900 <= o <= 0xFAFF
        or 0xFE10 <= o <= 0xFE4F
        or 0xFF00 <= o <= 0xFFEF
        or 0x20000 <= o <= 0x323AF
        or c in CJK_PUNCT
    )


def serif_class_names() -> set[str]:
    """从 CSS 解析出哪些 class 用了 var(--font-serif) / 'Fraunces' —— 这些类渲染的中文才需要楷体。"""
    classes: set[str] = set()
    css_files = (glob.glob("app/**/*.css", recursive=True)
                 + glob.glob("components/**/*.css", recursive=True))
    for f in css_files:
        if os.path.basename(f) == "fonts.css":   # @font-face 定义本身,跳过
            continue
        try:
            css = open(f, encoding="utf-8").read()
        except OSError:
            continue
        for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
            sel, body = m.group(1), m.group(2)
            if "--font-serif" in body or "Fraunces" in body:
                classes |= set(re.findall(r"\.([A-Za-z0-9_-]+)", sel))
    return classes


def collect_heading_chars() -> str:
    os.chdir(ROOT)
    blob: list[str] = []
    serif_classes = serif_class_names()
    for f in glob.glob("app/**/*.tsx", recursive=True) + glob.glob("components/**/*.tsx", recursive=True):
        try:
            lines = open(f, encoding="utf-8").read().splitlines()
        except OSError:
            continue
        t = "\n".join(lines)
        # 1) 所有 useDocumentTitle('中文', ...) 第一参 = 页面 H1
        blob += re.findall(r"useDocumentTitle\(\s*'([^']*)'", t)
        # 2) 凡是用衬线类的元素,收其文本(同行 + 后两行,覆盖 JSX 文本/tr() 跨行)
        for i, line in enumerate(lines):
            if "className" in line and any(c in line for c in serif_classes):
                blob.append(" ".join(lines[i:i + 3]))
    # 3) 数据驱动的标题文本(板块标题 / hero / 模块名等,不是 JSX 字面量,className 扫不到)。
    data_files: list[str] = []
    # landing-sections 可能是 .ts 或 .tsx,用 glob 匹配扩展名(曾写死 .ts 漏掉 .tsx 的"探")
    ls = glob.glob("lib/landing-sections.*")
    if not ls:
        print("WARN: lib/landing-sections.* not found")
    data_files += ls
    data_files += ["../shared/src/site_directory.ts", "lib/page-meta.ts"]
    # 固定路径含 [lang] 字面量,用 os.path.exists(glob 会把方括号当字符类)
    for f in ["app/[lang]/page.tsx", "app/[lang]/dev/page.tsx"]:
        if os.path.exists(f):
            data_files.append(f)
        else:
            print(f"WARN: data-heading source not found: {f}")
    for f in data_files:
        blob.append(open(f, encoding="utf-8").read())
    chars = sorted({c for c in "".join(blob) if keep(c)})
    return "".join(chars)


def ensure_ttf(ttf_name: str) -> str:
    path = os.path.join(FONTS_TMP, ttf_name)
    if not os.path.exists(path):
        os.makedirs(FONTS_TMP, exist_ok=True)
        url = f"{REL}/{ttf_name}"
        print(f"downloading {url}")
        urllib.request.urlretrieve(url, path + ".download")
        os.replace(path + ".download", path)
    return path


def unicode_ranges(points: set[int]) -> str:
    runs = []
    for cp in sorted(points):
        if runs and cp == runs[-1][1] + 1:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in runs)


def main() -> None:
    from fontTools import subset
    from fontTools.ttLib import TTFont

    common = {ord(c) for c in collect_heading_chars()}
    css = ["/* Generated by scripts/subset-cjk-heading.py; do not edit. */"]
    generated = set()
    for weight, ttf_name, out_name in WEIGHTS:
        ttf = ensure_ttf(ttf_name)
        with TTFont(ttf) as source:
            available = {cp for cp in source.getBestCmap() if keep(chr(cp))}
        primary = available & common
        groups = [(out_name, primary)]
        remaining = available - primary
        for block in sorted({cp // 512 for cp in remaining}):
            points = {cp for cp in remaining if cp // 512 == block}
            groups.append((f"lxgw-wenkai-{weight}-{block:03x}.woff2", points))
        covered = set()
        total = 0
        for name, points in groups:
            options = subset.Options()
            options.layout_features = []
            options.hinting = False
            options.recommended_glyphs = False
            options.recalc_timestamp = False
            font = TTFont(ttf, recalcTimestamp=False)
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(font)
            font.flavor = "woff2"
            out = Path(PUB_FONTS) / name
            font.save(out)
            font.close()
            # Verify actual emitted glyph coverage, not only requested ranges.
            with TTFont(out) as check:
                actual = set(check.getBestCmap())
            if actual != points or covered & actual:
                raise RuntimeError(f"Incorrect or overlapping coverage: {name}")
            covered |= actual
            data = out.read_bytes()
            total += len(data)
            digest = hashlib.sha256(data).hexdigest()[:12]
            generated.add(name)
            css.append("\n".join([
                "@font-face {",
                "  font-family: 'LXGW WenKai';",
                "  font-style: normal;",
                f"  font-weight: {'400' if weight == 400 else '500 600'};",
                "  font-display: swap;",
                f"  src: url('/fonts/{name}?v={digest}') format('woff2');",
                f"  unicode-range: {unicode_ranges(points)};",
                "}",
            ]))
        if covered != available:
            raise RuntimeError(f"Incomplete CJK coverage for weight {weight}")
        print(f"weight {weight}: {len(covered)} glyphs, {len(groups)} files, "
              f"{total // 1024} KiB total; common subset {len(primary)} glyphs")
    Path(ROOT, "app", "fonts-wenkai.css").write_text("\n\n".join(css) + "\n", encoding="utf-8")
    for old in Path(PUB_FONTS).glob("lxgw-wenkai-*.woff2"):
        if old.name not in generated:
            old.unlink()


if __name__ == "__main__":
    sys.exit(main())
