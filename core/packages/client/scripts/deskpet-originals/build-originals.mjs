import {mkdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createAnimator} from '../deskpet-animation.mjs';
import {ORIGINAL_CHARACTERS} from './characters/index.mjs';
import {ORIGINAL_SCENES} from './scenes.mjs';
import {motion} from './motion.mjs';
import {props} from './props.mjs';
const here=dirname(fileURLToPath(import.meta.url));
const out=resolve(here,'../../public/deskpet/originals');
const xml=(s)=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const files=new Map(),scenes=[];
if(ORIGINAL_CHARACTERS.length!==12 || new Set(ORIGINAL_CHARACTERS.map(c=>c.id)).size!==12)throw Error('Expected 12 unique characters');
for(const ch of ORIGINAL_CHARACTERS){
  for(const [index,scene] of ORIGINAL_SCENES.entries()){
    const {a,styles}=createAnimator(`op${ch.number}s${index+1}`,scene.duration);
    const plan=motion(ch,scene);
    const used=new Set(),pivots={};
    const joint=(name,art,pivot)=>{
      if(!Array.isArray(pivot)||pivot.some(n=>!Number.isFinite(n)))throw Error(`${ch.id}: invalid ${name} pivot`);
      used.add(name);
      pivots[name]=pivot;
      return `<g data-joint="${name}">${a(art,plan[name],`${pivot[0]}px ${pivot[1]}px`,ch.pixel?'steps(10,end)':'cubic-bezier(.4,0,.25,1)')}</g>`;
    };
    const art=ch.render({joint});
    for(const name of ['body','head','left','right','blink','gaze'])if(!used.has(name))throw Error(`${ch.id}: missing ${name}`);
    const {back,front}=props(ch,scene,a,{plan,pivots});
    const file=`${ch.id}/${String(index+1).padStart(2,'0')}-${scene.id}.svg`;
    const markup=`<!-- Generated by scripts/deskpet-originals/build-originals.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" width="240" height="240" viewBox="0 0 240 240" role="img" aria-labelledby="title desc" data-character="${ch.id}" data-scene="${scene.id}" data-duration="${scene.duration}">
<title id="title">${xml(ch.zh+' '+scene.zh+' / '+ch.en+' '+scene.en)}</title><desc id="desc">${xml(scene.description+' '+scene.descriptionEn)}</desc>
<style>${styles.join('\n')}
@media(prefers-reduced-motion:reduce){g{animation-play-state:paused!important;animation-delay:-${scene.poster*scene.duration}s!important}}
</style><ellipse cx="120" cy="${Math.min(207,ch.anchors.feet[1]+4)}" rx="66" ry="6" fill="#263444" opacity=".12"/>
${back}${art}${front}</svg>\n`;
    if(/NaN|undefined|Infinity/.test(markup))throw Error(`Invalid ${file}`);
    files.set(file,markup);
    // Non-handed animals use species-appropriate copy without imaginary paws.
    const copy=ch.id==='snail'&&scene.id==='hello'?{description:'伸出眼柄，轻轻晃两下，像是在跟你打招呼。',descriptionEn:'Raises its eyestalks and gives a little greeting.'}:{};
    scenes.push({...scene,...copy,file,character:ch.id});
  }
}
const characters=ORIGINAL_CHARACTERS.map(({id,number,zh,en,pixel,locomotion,gesture})=>({id,number,zh,en,pixel,locomotion,gesture}));
files.set('manifest.json',JSON.stringify({version:'1',characters,scenes},null,2)+'\n');
if(scenes.length!==576)throw Error('Expected 576 scenes');
if(process.argv.includes('--check')){
  const stale=[...files].filter(([file,content])=>!existsSync(join(out,file))||readFileSync(join(out,file),'utf8')!==content).map(([file])=>file);
  if(stale.length)throw Error(`Stale original-pet assets: ${stale.join(', ')}`);
  console.log('576 original pet animations and manifest are current.');
}else{
  for(const [file,content]of files){mkdirSync(dirname(join(out,file)),{recursive:true});writeFileSync(join(out,file),content);}
  console.log(`Built 12 characters × 48 stories = ${scenes.length} animated SVGs (${[...files.values()].reduce((n,s)=>n+Buffer.byteLength(s),0)} bytes).`);
}
